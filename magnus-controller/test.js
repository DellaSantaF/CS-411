const assert = require('node:assert/strict');
const {force,step,coefficientFromSpin} = require('./physics.js');
const near = (a,b,t=1e-9) => assert.ok(Math.abs(a-b)<t, `${a} != ${b}`);
const p={liftCoefficient:0.5,density:1.2,area:0.04,mass:0.4};
const s={x:0,y:0,vx:10,vy:0};
const f=force(s,p); near(f.x,0); near(f.y,1.2); near(f.magnitude,1.2);
near(force({...s,vx:20},p).magnitude,4*f.magnitude);
near(force(s,{...p,liftCoefficient:-0.5}).y,-f.y);
assert.deepEqual(force({...s,vx:0},p),{x:0,y:0,magnitude:0});
const next=step(s,p,1); near(Math.hypot(next.vx,next.vy),10); assert.ok(next.y>0); near(next.x,10*Math.sin(0.3)/0.3); near(next.y,10*(1-Math.cos(0.3))/0.3);
const backwards=step(s,{...p,liftCoefficient:-0.5},1); near(backwards.y,-next.y);
assert.deepEqual(step(s,{...p,liftCoefficient:0},2),{x:20,y:0,vx:10,vy:0});
let many=s; for(let i=0;i<100;i++) many=step(many,p,0.01); near(many.x,next.x); near(many.y,next.y);
assert.throws(()=>step(s,{...p,mass:0},1),RangeError); assert.throws(()=>step(s,p,-1),RangeError);
near(coefficientFromSpin({radius:0.1,spin:10,relativeAirSpeed:10}),0.15);
near(coefficientFromSpin({radius:0.1,spin:-10,relativeAirSpeed:10}),-0.15);
near(coefficientFromSpin({radius:0.1,spin:100,relativeAirSpeed:1}),0.6);
near(coefficientFromSpin({radius:0.1,spin:100,relativeAirSpeed:1,scale:0.5}),0.3);
assert.throws(()=>coefficientFromSpin({radius:-1,spin:1,relativeAirSpeed:1}),RangeError);
console.log('Magnus physics checks passed');
